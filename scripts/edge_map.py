"""Generate docs/EDGE_MAP.md: every queued method and registered round placed in one edge family.

Each family records who pays the edge, its net P&L equation, the binding constraint, the checks that catch a fake
version of it, the gaps and the next refinement. The record (methods by status, rounds by verdict) is computed from
registry/methods.csv and registry/rounds.csv, so the map stays a view of the live queue, never a second queue.

Inputs: registry/edge_families.csv (one row per family) and registry/edge_map_links.csv (item -> family; an item is
a method id M### or a round id R### that no method links). A method's rounds come from its `rid` field.

usage: python scripts/edge_map.py           write docs/EDGE_MAP.md
       python scripts/edge_map.py --check   exit 1 if the file differs from what the registry generates
"""
import argparse
import csv
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path("docs/EDGE_MAP.md")
RID = re.compile(r"R\d{3}")
OPEN = ("UNTESTED", "QUEUED", "BLOCKED")
LIVE = ("RUNNING", "ARMED", "REGISTERED", "PLANNED")

HEADER = """# Edge map: every way the lab could make money, and what each one has shown

Generated by `scripts/edge_map.py` from `registry/edge_families.csv`, `registry/edge_map_links.csv`,
`registry/methods.csv` and `registry/rounds.csv`. Do not edit by hand; edit the registry files and regenerate.
The live queue stays `registry/methods.csv`; this file only places each method and round in one family.

## The master equation
Every strategy the lab can run, on any venue, nets

```
net = sum over trades [ d x dP/P            price move in the position's direction
                      + Phi                 funding and settlements received
                      + R ]                 rebates, incentives, collateral yield
    - sum over trades [ fee + spread + impact(size) + latency slippage ]
    - financing - tail losses (liquidations, delistings, gaps)
```

An edge is a term that is positive in expectation *after* the cost line, for a reason that should persist (someone
pays it), and that survives selection: its t-statistic is read against `registry.program_trials()`, not its own null.
Each family below names the term it lives in, who pays it, and the constraint that has decided its verdicts so far.

## Fake-edge checklist (apply to every result, positive or null)
1. **Cost:** a band or average cost instead of each coin's book at the minute of the trade (audit F1, F7); the web
   fee for API fills (F3, F8); maker fills assumed at the touch.
2. **Prices:** stale or delisted prices (F4, F5); last trade vs mark; fills at a bar close that was not tradable.
3. **Time:** data used before it was published; DST and session windows (D1); late-computed hours (F9); joining
   different windows (F10); a payment credited before the exit price that earns it (F2).
4. **Accounting:** constant-notional vs fixed-quantity marks (H2); funding-interval scaling (H3, R384);
   day-weighted vs trade-weighted means (H4); cluster vs leg weighting (H5).
5. **Universe:** survivorship; contract name mis-joins (H6); a freshness rule that depends on bar length (H1);
   reserved or already-read rows.
6. **Selection:** best of many without the program's trial count; post hoc picks; a sum carried by a few days
   (top-10-day share); leave-two-coins-out and trimmed means.
7. **Statistics:** test size (F11); clustering that does nothing (D3); missing trial counts (D4); short samples.
8. **Execution:** capacity on thin coins; margin and liquidation per venue; venue access.

The audit ids refer to `docs/reviews/hidden_edge_audit_20261104.md`. A null can be fake too: H1 hid dYdX's carry.

## Refining order (2026-11-04)
The map is refined one family at a time, cheapest informative test first, each as a registered lane:
1. **P1 carry:** M468 venue-neutral engine, then M469 at measured book costs, with the collateral-yield term (V1).
   It is the only family confirmed on unread data.
2. **P4 market making on zero-fee venues:** M474, passive quotes replayed on the recorded raw tape and Lighter
   trades with a conservative queue model. The payer is clear, and only directional maker entries were tested.
3. **F4 skill transfer:** M466 after the public Hyperliquid vault download (about 300 MB). It is the largest family
   with no test.
4. **R2 TradFi perps at the reopen:** M447 and M321 on held data.
5. **E3 supply:** M297 post-airdrop short on held data.
6. **Forward lanes:** read with the dead-leg (M470) and late-hour (M473) splits.

## Decisions taken under the owner's delegation (2026-11-04)
- **Calibration orders:** not now. Public book snapshots measure costs first, at no risk; owner-placed orders come
  only when a lane is about to trade, after paper and `lab.gate.go_real()`.
- **Hyperliquid vaults (~300 MB, public):** yes, bounded, for F4/M466.
- **Lighter accounts (~1 GB):** not in full; a sample only, after the vault test reads.
- **Upbit hourly candles:** estimate the size from metadata first; download only if it is small.
"""


def _rows(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def load(root=ROOT):
    root = Path(root)
    families = _rows(root / "registry/edge_families.csv")
    links = _rows(root / "registry/edge_map_links.csv")
    methods = {r["id"]: r for r in _rows(root / "registry/methods.csv")}
    rounds = {r["id"]: r for r in _rows(root / "registry/rounds.csv")}
    return families, links, methods, rounds


def problems(families, links, methods, rounds):
    """Structural errors: unknown family, unknown item, an item placed twice."""
    ids = {f["id"] for f in families}
    out = []
    seen = Counter(link["item"] for link in links)
    out += [f"{item} is placed {n} times" for item, n in sorted(seen.items()) if n > 1]
    for link in links:
        if link["family"] not in ids:
            out.append(f"{link['item']} points to unknown family {link['family']}")
        if link["item"] not in methods and link["item"] not in rounds:
            out.append(f"{link['item']} is not in methods.csv or rounds.csv")
    return out


def summarize(families, links, methods, rounds):
    members = defaultdict(list)
    for link in links:
        members[link["family"]].append(link["item"])
    placed_rounds = set()
    table = []
    for fam in families:
        items = members[fam["id"]]
        ms = [i for i in items if i in methods]
        rs = {i for i in items if i in rounds}
        for m in ms:
            rs |= {r for r in RID.findall(methods[m]["rid"]) if r in rounds}
        placed_rounds |= rs
        by_verdict = defaultdict(list)
        for r in sorted(rs, key=lambda x: int(x[1:])):
            row = rounds[r]
            key = "running" if row["status"] in LIVE and row["verdict"] == "PENDING" else row["verdict"].lower()
            by_verdict[key].append(r)
        table.append(dict(fam, methods=ms, method_status=Counter(methods[m]["status"] for m in ms),
                          rounds=by_verdict))
    unplaced_methods = sorted(set(methods) - {link["item"] for link in links}, key=lambda x: int(x[1:]))
    unplaced_rounds = sorted(set(rounds) - placed_rounds, key=lambda x: int(x[1:]))
    return table, unplaced_methods, unplaced_rounds


def _ids(xs):
    return ", ".join(xs) if xs else "none"


def render(root=ROOT):
    families, links, methods, rounds = load(root)
    errors = problems(families, links, methods, rounds)
    if errors:
        raise ValueError("; ".join(errors))
    table, unplaced_methods, unplaced_rounds = summarize(families, links, methods, rounds)
    out = [HEADER, "## Overview", "",
           "| Id | Family | Group | Methods (open) | Confirmed | Partial | Null | Running |",
           "|---|---|---|---|---|---|---|---|"]
    for f in table:
        n_open = sum(f["method_status"][s] for s in OPEN)
        r = f["rounds"]
        out.append(f"| {f['id']} | {f['family']} | {f['group']} | {len(f['methods'])} ({n_open}) | "
                   f"{len(r['confirmed'])} | {len(r['partial'])} | {len(r['null'])} | {len(r['running'])} |")
    out += ["", "Rounds are counted in every family whose methods link them (the R185 atlas, for example, is a gross "
            "screen linked from many families). Confirmed means confirmed by that round's own frozen rule, which "
            "for R185/R192/R195 was a gross (before-cost) screen.", ""]
    for f in table:
        status = ", ".join(f"{k} {v}" for k, v in sorted(f["method_status"].items())) or "none"
        r = f["rounds"]
        other = {k: v for k, v in r.items() if k not in ("confirmed", "partial", "null", "running")}
        out += [f"## {f['id']} {f['family']} ({f['group']})", "",
                f"- **Who pays:** {f['payer']}",
                f"- **Equation:** `{f['equation']}`",
                f"- **Binding constraint:** {f['binding_constraint']}",
                f"- **Fake-edge checks:** {f['fake_edge_checks']}",
                f"- **Methods ({len(f['methods'])}):** {status}. {_ids(f['methods'])}",
                f"- **Rounds:** confirmed {_ids(r['confirmed'])}; partial {_ids(r['partial'])}; "
                f"null {_ids(r['null'])}; running {_ids(r['running'])}"
                + "".join(f"; {k} {_ids(v)}" for k, v in sorted(other.items())),
                f"- **Reading:** {f['reading']}",
                f"- **Gaps:** {f['gaps']}",
                f"- **Next:** {f['next']}", ""]
    out += ["## Not yet placed", "",
            f"- **Methods:** {_ids(unplaced_methods)}",
            f"- **Rounds:** {_ids(unplaced_rounds)}", "",
            "Place a new method by adding a row to `registry/edge_map_links.csv`, then regenerate.", ""]
    return "\n".join(out)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true")
    a = p.parse_args(argv)
    text = render(ROOT)
    path = ROOT / OUT
    if a.check:
        if not path.exists() or path.read_text() != text:
            print(f"STALE {OUT}")
            return 1
        print("Edge map matches the registry.")
        return 0
    path.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
